#!/bin/bash

# Переводим терминал в режим отображения ошибок, если что-то пойдет не так
set -e

echo "=================================================="
echo "   ПЕРЕЗАПУСК СИСТЕМЫ: ROS2 BAG & RUST VIEWER     "
echo "=================================================="

# 1. Сбрасываем старый мусор и контейнеры
echo "► [1/3] Остановка активных контейнеров..."
docker compose down

# 2. Очищаем кэш сборки Docker (опционально, гарантирует чистоту)
echo "► [2/3] Сборка и компиляция Rust-приложения..."
docker compose build --no-cache rust_viewer

# 3. Запускаем оба сервиса на хост-сети
echo "► [3/3] Запуск трансляции датасета и вьювера..."
echo "--------------------------------------------------"
docker compose up
